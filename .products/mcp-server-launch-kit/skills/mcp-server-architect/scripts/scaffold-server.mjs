#!/usr/bin/env node
/**
 * scaffold-server — generate a dependency-free, stdio MCP server from mcp.spec.json.
 *
 * Usage: node scaffold-server.mjs <mcp.spec.json> [--out <dir>] [--force]
 * Exit: 0 on success, 1 on invalid spec or existing output without --force.
 *
 * Generated servers implement initialize / tools/list / tools/call over newline-delimited
 * JSON-RPC 2.0 and validate required arguments. Tool handlers are dry-run echoes until
 * you wire real logic — the protocol, schemas, and security posture are real.
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { exists, readJson, validateSpec } from './lib.mjs';

const argv = process.argv.slice(2);
let specPath = null;
let outDir = null;
let force = false;
for (let i = 0; i < argv.length; i += 1) {
  if (argv[i] === '--out') outDir = argv[++i];
  else if (argv[i] === '--force') force = true;
  else specPath = argv[i];
}
if (!specPath) {
  console.error('Usage: node scaffold-server.mjs <mcp.spec.json> [--out <dir>] [--force]');
  process.exit(1);
}

const spec = await readJson(path.resolve(specPath));
if (!spec) {
  console.error(`Cannot parse spec: ${specPath}`);
  process.exit(1);
}
const errors = validateSpec(spec);
if (errors.length) {
  console.error('Spec is invalid:');
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

const target = path.resolve(outDir || spec.name);
if (await exists(target)) {
  const entries = await fs.readdir(target);
  if (entries.length && !force) {
    console.error(`Output directory is not empty: ${target}. Pass --force to overwrite generated files.`);
    process.exit(1);
  }
}
await fs.mkdir(path.join(target, 'test'), { recursive: true });

const toolsSource = `// Generated by mcp-server-architect. Tool contracts come from mcp.spec.json.
// Handlers are dry-run echoes: replace each body with real logic, keep the schema.

export const TOOLS = [
${spec.tools
  .map(
    (tool) => `  {
    name: ${JSON.stringify(tool.name)},
    description: ${JSON.stringify(tool.description)},
    inputSchema: ${JSON.stringify(tool.inputSchema, null, 2).replace(/\n/g, '\n    ')},
    async handler(args) {
      return { tool: ${JSON.stringify(tool.name)}, dryRun: true, received: args };
    },
  },`,
  )
  .join('\n')}
];
`;

const serverSource = `#!/usr/bin/env node
import { TOOLS } from './tools.mjs';

const PROTOCOL_VERSION = '2024-11-05';
const SERVER_INFO = { name: ${JSON.stringify(spec.name)}, version: ${JSON.stringify(spec.version)} };

function send(message) {
  process.stdout.write(JSON.stringify(message) + '\\n');
}

function validate(schema, args) {
  const errors = [];
  if (!schema || schema.type !== 'object') return errors;
  for (const key of schema.required || []) {
    if (args[key] === undefined) errors.push('missing required argument: ' + key);
  }
  for (const [key, definition] of Object.entries(schema.properties || {})) {
    const value = args[key];
    if (value === undefined) continue;
    const type = definition.type;
    if (type === 'string' && typeof value !== 'string') errors.push(key + ' must be a string');
    if (type === 'number' && typeof value !== 'number') errors.push(key + ' must be a number');
    if (type === 'boolean' && typeof value !== 'boolean') errors.push(key + ' must be a boolean');
    if (type === 'array' && !Array.isArray(value)) errors.push(key + ' must be an array');
    if (type === 'object' && (typeof value !== 'object' || Array.isArray(value))) errors.push(key + ' must be an object');
  }
  return errors;
}

async function handle(request) {
  const { id, method, params } = request;

  if (method === 'initialize') {
    return {
      jsonrpc: '2.0',
      id,
      result: {
        protocolVersion: PROTOCOL_VERSION,
        capabilities: { tools: { listChanged: false } },
        serverInfo: SERVER_INFO,
      },
    };
  }

  if (method === 'notifications/initialized') return null;
  if (method === 'ping') return { jsonrpc: '2.0', id, result: {} };

  if (method === 'tools/list') {
    return {
      jsonrpc: '2.0',
      id,
      result: {
        tools: TOOLS.map(({ name, description, inputSchema }) => ({ name, description, inputSchema })),
      },
    };
  }

  if (method === 'tools/call') {
    const name = params?.name;
    const tool = TOOLS.find((candidate) => candidate.name === name);
    if (!tool) return { jsonrpc: '2.0', id, error: { code: -32602, message: 'Unknown tool: ' + String(name) } };

    const args = params?.arguments || {};
    const problems = validate(tool.inputSchema, args);
    if (problems.length) {
      return {
        jsonrpc: '2.0',
        id,
        result: { content: [{ type: 'text', text: JSON.stringify({ error: 'invalid_arguments', details: problems }) }], isError: true },
      };
    }

    try {
      const output = await tool.handler(args);
      return { jsonrpc: '2.0', id, result: { content: [{ type: 'text', text: JSON.stringify(output) }] } };
    } catch (error) {
      return {
        jsonrpc: '2.0',
        id,
        result: { content: [{ type: 'text', text: JSON.stringify({ error: error.message }) }], isError: true },
      };
    }
  }

  return { jsonrpc: '2.0', id, error: { code: -32601, message: 'Method not found: ' + String(method) } };
}

let buffer = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', async (chunk) => {
  buffer += chunk;
  let index;
  while ((index = buffer.indexOf('\\n')) >= 0) {
    const line = buffer.slice(0, index).trim();
    buffer = buffer.slice(index + 1);
    if (!line) continue;
    let request;
    try {
      request = JSON.parse(line);
    } catch {
      continue;
    }
    const response = await handle(request);
    if (response) send(response);
  }
});
`;

const packageJson = {
  name: spec.name,
  version: spec.version,
  private: true,
  type: 'module',
  description: spec.description,
  engines: { node: '>=18' },
  scripts: { start: 'node server.mjs', test: 'node test/smoke.test.mjs' },
};

const readme = `# ${spec.name}

${spec.description}

Generated by **MCP Server Launch Kit**. Dependency-free stdio MCP server (JSON-RPC 2.0).

## Run

\`\`\`bash
npm start
\`\`\`

Protocol version: \`2024-11-05\`. Transport: newline-delimited JSON on stdio.

## Tools

| Tool | Description |
| --- | --- |
${spec.tools.map((tool) => `| \`${tool.name}\` | ${tool.description.replace(/\|/g, '\\|')} |`).join('\n')}

## Wire your logic

Each handler in \`tools.mjs\` returns a dry-run echo. Replace the body with real logic, keep the
\`inputSchema\` unchanged, and keep validation in \`server.mjs\` — the schema is the contract clients
read during \`tools/list\`.

## Test

\`\`\`bash
npm test
\`\`\`

The smoke test spawns the server, performs \`initialize\`, \`tools/list\`, and a \`tools/call\` for the
first tool. Run it after every handler change.

## Security notes

- No network listener: stdio only, so there is no unauthenticated port.
- Required arguments are validated before any handler runs.
- Never log environment secrets; log presence flags instead.
`;

const smokeTest = `import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const serverPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'server.mjs');
const child = spawn(process.execPath, [serverPath], { stdio: ['pipe', 'pipe', 'inherit'] });
const responses = new Map();
let buffer = '';

child.stdout.setEncoding('utf8');
child.stdout.on('data', (chunk) => {
  buffer += chunk;
  let index;
  while ((index = buffer.indexOf('\\n')) >= 0) {
    const line = buffer.slice(0, index).trim();
    buffer = buffer.slice(index + 1);
    if (!line) continue;
    const message = JSON.parse(line);
    responses.set(message.id, message);
  }
});

function send(message) {
  child.stdin.write(JSON.stringify(message) + '\\n');
}

async function waitFor(id, timeoutMs = 3000) {
  const started = Date.now();
  while (!responses.has(id)) {
    if (Date.now() - started > timeoutMs) throw new Error('Timed out waiting for response ' + id);
    await new Promise((resolve) => setTimeout(resolve, 10));
  }
  return responses.get(id);
}

send({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'smoke', version: '0.0.0' } } });
const init = await waitFor(1);
assert.equal(init.result.protocolVersion, '2024-11-05');
assert.equal(init.result.serverInfo.name, ${JSON.stringify(spec.name)});
send({ jsonrpc: '2.0', method: 'notifications/initialized' });

send({ jsonrpc: '2.0', id: 2, method: 'tools/list' });
const list = await waitFor(2);
assert.equal(list.result.tools.length, ${spec.tools.length});
assert.deepEqual(list.result.tools.map((tool) => tool.name).sort(), ${JSON.stringify(spec.tools.map((tool) => tool.name).sort())});

const first = ${JSON.stringify(spec.tools[0])};
const required = first.inputSchema.required || [];
if (required.length) {
  send({ jsonrpc: '2.0', id: 3, method: 'tools/call', params: { name: first.name, arguments: {} } });
  const invalid = await waitFor(3);
  assert.equal(invalid.result.isError, true);
}

const sample = {};
for (const key of required) {
  const type = first.inputSchema.properties[key]?.type;
  sample[key] = type === 'number' ? 1 : type === 'boolean' ? true : type === 'array' ? [] : 'sample';
}
send({ jsonrpc: '2.0', id: 4, method: 'tools/call', params: { name: first.name, arguments: sample } });
const call = await waitFor(4);
assert.equal(call.result.isError, undefined);
assert.equal(JSON.parse(call.result.content[0].text).tool, first.name);

child.kill();
console.log('MCP smoke test passed: initialize, tools/list, tools/call, validation.');
`;

await fs.writeFile(path.join(target, 'tools.mjs'), toolsSource);
await fs.writeFile(path.join(target, 'server.mjs'), serverSource);
await fs.writeFile(path.join(target, 'package.json'), `${JSON.stringify(packageJson, null, 2)}\n`);
await fs.writeFile(path.join(target, 'mcp.spec.json'), `${JSON.stringify(spec, null, 2)}\n`);
await fs.writeFile(path.join(target, 'README.md'), readme);
await fs.writeFile(path.join(target, 'test', 'smoke.test.mjs'), smokeTest);

console.log(`Scaffolded ${spec.name} v${spec.version} with ${spec.tools.length} tool(s) at ${target}`);
console.log('Next: npm test, then replace dry-run handlers in tools.mjs.');
